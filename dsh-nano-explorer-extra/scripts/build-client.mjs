import { spawnSync } from 'node:child_process'
import { readFileSync, writeFileSync, rmSync, existsSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

/**
 * Bake this plugin's rows of security/route-sensitivity.json into
 * `src/host/route-table.js` (T-O-13 / P1-04): the running host cannot reach
 * the repo root, so the route table ships as a baked constant bundled into
 * lib/host.js. Fails the build when the ledger is missing or has no rows for
 * this package.
 */
function bakeRouteTable() {
  const repoRoot = join(root, '..')
  const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
  const ledger = JSON.parse(readFileSync(join(repoRoot, 'security', 'route-sensitivity.json'), 'utf8'))
  const rows = (ledger.routes ?? []).filter(row => row.plugin === pkg.name)
  if (rows.length === 0) {
    console.error(`route-table bake: no rows for ${pkg.name} in security/route-sensitivity.json`)
    process.exit(1)
  }
  const source = `/** GENERATED by scripts/build-client.mjs from security/route-sensitivity.json (T-O-13).\n * Do not edit: the running host only sees this baked constant. */\nexport const PLUGIN = ${JSON.stringify(pkg.name)}\n\nexport const ROUTE_TABLE = ${JSON.stringify(rows, null, 2)}\n`
  const out = join(root, 'src', 'host', 'route-table.js')
  mkdirSync(dirname(out), { recursive: true })
  writeFileSync(out, source)
}

// Route table first: the host bundle below imports it.
bakeRouteTable()

// Prefer the locked devDependency binary; fall back to npx only when it is not
// installed, so a release build never pulls a drifted toolchain (review-01 R12).
const local = join(root, 'node_modules', '.bin', 'esbuild')

const { version } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
/** Compile-time package version, so both halves can report `meta.version` to perf-review. */
const versionDefine = `--define:__NXE_VERSION__=${JSON.stringify(version)}`

/**
 * Bundle one entry and fail the build when esbuild rejects it.
 * @param {string} entry - source entry, relative to the package root.
 * @param {string} outfile - output path, relative to the package root.
 * @param {string[]} extra - additional esbuild flags.
 */
function bundle(entry, outfile, extra) {
  const argv = [entry, '--bundle', ...extra, `--outfile=${join(root, outfile)}`]
  const built = existsSync(local)
    ? spawnSync(local, argv, { cwd: root, stdio: 'inherit' })
    : spawnSync('npx', ['--yes', 'esbuild@0.25.0', ...argv], { cwd: root, stdio: 'inherit' })
  if (built.status !== 0) process.exit(built.status ?? 1)
}

// Host half: plain ESM for Node. No --packages=external: the only bare import the host
// sources carry is dsh-performance-review, and it MUST be bundled — the development
// instance copies lib/ but not node_modules, so a runtime bare import would fail to
// resolve (spec §3.3/F3). node:* builtins stay external automatically on platform=node.
bundle('src/host/entry.js', 'lib/host.js', [
  '--format=esm',
  '--platform=node',
  versionDefine,
])

// Browser half: an IIFE wrapped in the client module-loader factory format.
bundle('src/client/index.js', 'lib/client.body.js', [
  '--format=iife',
  '--global-name=__nxeExport',
  '--minify',
  '--platform=browser',
  '--external:react',
  '--external:react-dom',
  '--external:react-dom/client',
  // Shared through PLATFORM_MODULES: the shell seeds this identity, so the bundle must not copy it.
  '--external:@deepseek-ai/dsh-client-ui-primitives',
  versionDefine,
])

const body = join(root, 'lib/client.body.js')
// The bundle assigns its exports to one named global, so the factory returns that object rather than
// guessing at internal binding names: those survive minification only by luck.
const source = readFileSync(body, 'utf8').trim()
writeFileSync(join(root, 'lib/client.js'), `window.__ModuleLoader__.load({
	id: "dsh-nano-explorer-extra",
	factory: (require) => {
${source}
		return __nxeExport;
	}
});
`)
rmSync(body)
