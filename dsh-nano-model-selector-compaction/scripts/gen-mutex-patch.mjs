#!/usr/bin/env node
/**
 * Regenerate cordis.patch.yml from the four upstream agent-preset patch files.
 *
 * Mechanism (DNMS01 QNA R-16): cordis patch grammar cannot address preset
 * `config.plugins` sub-rows, so mutual exclusion is expressed by whole-object
 * `config` replacement. This script replays each preset's `config.plugins`
 * verbatim, rewriting only the `id: compaction` group so that our Provider row
 * mounts and the factory `compaction-basic` row is `disabled: true`.
 *
 * Usage:
 *   node scripts/gen-mutex-patch.mjs --context /path/to/presets/dir
 *
 * Re-run whenever the pinned `engines.dsh` window moves upstream.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const PRESETS = ['standard', 'ptc', 'minimal', 'cordis']
const PRESET_IDS = {
  standard: 'preset-standard', ptc: 'preset-ptc',
  minimal: 'preset-minimal', cordis: 'preset-cordis',
}
const PROVIDER_ROW = {
  id: 'nano-model-selector-compaction',
  name: 'dsh-nano-model-selector-compaction',
}

const args = process.argv.slice(2)
const ctxDir = args[args.indexOf('--context') + 1] ??
  '/Users/seanz/Documents/dsh-plugins/context/deepseek-harness/packages/bundle/web-app/presets'

// yaml is resolved from the context checkout's node_modules (it is a vendored
// dep of the app); fall back to the asar extraction used for the P0 spikes.
const yamlCandidates = [
  join(process.env.HOME ?? '', 'Documents/dsh-plugins/context/deepseek-harness/node_modules/yaml'),
  '/tmp/dnms01-asar/dsh/node_modules/yaml',
  join(process.env.HOME ?? '', '.dsh-dev/profiles/web/node_modules/yaml'),
]
let parse, stringify
for (const dir of yamlCandidates) {
  try {
    const m = await import(join(dir, 'dist', 'index.js'))
    parse = m.parse ?? m.default?.parse
    stringify = m.stringify ?? m.default?.stringify
    if (parse && stringify) break
  } catch { /* try next */ }
}
if (!parse || !stringify) {
  console.error('gen-mutex-patch: could not resolve yaml; pass an explicit --context with a node_modules containing yaml')
  process.exit(1)
}

const header = `# Mutually-exclusive async-compaction overlay (DNMS01, -10/-14; QNA R-16).
#
# Generated by scripts/gen-mutex-patch.mjs — do not hand-edit the preset blocks.
# Each preset row below is a WHOLE-object config.plugins replay of the upstream
# preset file; only the "id: compaction" group differs: our Provider row is
# inserted and the factory compaction-basic row is disabled. OFF = remove this
# bundle from dsh.profile.bundles and the native composition returns.
#
# Source presets: ${ctxDir}/\${standard,ptc,minimal,cordis}.patch.yml
#
`

const patches = []
const jsTag = { tag: 'tag:yaml.org,2002:js', resolve: v => v }
for (const key of PRESETS) {
  const file = join(ctxDir, `${key}.patch.yml`)
  const rows = parse(readFileSync(file, 'utf8'), { customTags: [jsTag] })
  const insert = rows.find(p => Array.isArray(p.insert))
  const preset = insert.insert.find(r => r.id === PRESET_IDS[key])
  if (!preset) throw new Error(`preset row ${PRESET_IDS[key]} not found in ${file}`)
  const plugins = preset.config.plugins
  const ci = plugins.findIndex(r => r.id === 'compaction')
  if (ci < 0) throw new Error(`id:compaction group not found in preset ${key}`)
  const group = plugins[ci]
  const rows2 = group.config.map(row =>
    row.id === 'compaction-basic' ? { ...row, disabled: true } : row)
  const patched = { ...group, config: [PROVIDER_ROW, ...rows2] }
  const replay = plugins.map((r, i) => (i === ci ? patched : r))
  patches.push({ id: PRESET_IDS[key], config: { ...preset.config, plugins: replay } })
}

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'cordis.patch.yml')
let text = stringify(patches, { customTags: [jsTag] })
// yaml loses the !!js tag on round-trip; restore it wherever the source rows
// carried a code expression (identifiable by a leading `!` or `process.`/`ctx.`
// expression that upstream only ever writes as a !!js literal).
text = text.replace(
  /^(\s*disabled: )(?!!!js )(.*(?:process\.|ctx\.).*)$/gm,
  (_m, p, v) => `${p}!!js ${v}`,
)
text = text.replace(
  /^(\s*-\s*)"(!!js .*)"$/gm,
  '$1$2',
)
writeFileSync(out, header + text)
console.log(`wrote ${out} (${patches.length} preset replays)`)
