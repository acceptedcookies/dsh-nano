#!/usr/bin/env node
/**
 * Regenerate cordis.patch.yml from the four upstream agent-preset patch files.
 *
 * Mechanism (DNMS01 QNA R-16): cordis patch grammar cannot address preset
 * `config.plugins` sub-rows, so mutual exclusion is expressed by whole-object
 * `config` replacement. This script replays each preset's `config.plugins`
 * verbatim, rewriting only the `id: compaction` group so that our Provider row
 * mounts and the factory `compaction-basic` row is `disabled: true`.
 *
 * Usage:
 *   node scripts/gen-mutex-patch.mjs --context /path/to/presets/dir
 *
 * Re-run whenever the pinned `engines.dsh` window moves upstream.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const PRESETS = ['standard', 'ptc', 'minimal', 'cordis']
const PRESET_IDS = {
  standard: 'preset-standard', ptc: 'preset-ptc',
  minimal: 'preset-minimal', cordis: 'preset-cordis',
}
const PROVIDER_ROW = {
  id: 'nano-model-selector-compaction',
  name: 'dsh-nano-model-selector-compaction',
}
/**
 * The read-only checkpoint inspection tool (ACE-1117 -09①/②): a SECOND row
 * of the same package through its `./tools` export, mounted at preset TOP
 * level — never inside `id: compaction` (the isolate must not see it, and the
 * engine row stays single-purpose). It lives and dies with the Provider row:
 * OFF removes this overlay entirely.
 */
const TOOLS_ROW = {
  id: 'inspect-checkpoint',
  name: 'dsh-nano-model-selector-compaction/tools',
}

/**
 * Rows present in the newest upstream presets but absent from older releases
 * inside the engines.dsh window. A full replay would mount a package that the
 * target installation does not ship and take the whole preset down (the GUI
 * reports "agent-preset/invalid: <row>: never started"). Emit a !!js guard so
 * the row self-disables when its package cannot be resolved from the preset
 * layer's baseUrl. Keep this list minimal: name resolution failures are the
 * only fatal class; additive config keys on existing plugins are harmless.
 */
// id → package name for rows added after the oldest release inside
// engines.dsh; extend when upstream presets gain more rows.
const VERSION_GUARDED_ROWS = new Map([
  ['tool-office', '@deepseek-ai/dsh-tool-office'],
])
// resolve() throws MODULE_NOT_FOUND on absent packages, so the guard must be
// an IIFE with try/catch; a bare ternary would re-throw during disabled-eval.
// Emitted through a placeholder: yaml stringify would quote a literal "!!js…"
// scalar and drop the tag; the post-pass below restores the real `!!js` line.
const guardPlaceholder = pkg => `__DNMSC_GUARD_${pkg.replace(/[^a-zA-Z]/g, '_')}__`
const guardLine = pkg =>
  `disabled: !!js (() => { try { process.getBuiltinModule('node:module').createRequire(baseUrl).resolve('${pkg}/package.json'); return false } catch { return true } })()`

const args = process.argv.slice(2)
const ctxDir = args[args.indexOf('--context') + 1] ??
  '/Users/seanz/Documents/dsh-plugins/context/deepseek-harness/packages/bundle/web-app/presets'

// yaml is resolved from the context checkout's node_modules (it is a vendored
// dep of the app); fall back to the asar extraction used for the P0 spikes.
const yamlCandidates = [
  join(process.env.HOME ?? '', 'Documents/dsh-plugins/context/deepseek-harness/node_modules/yaml'),
  '/tmp/dnms01-asar/dsh/node_modules/yaml',
  join(process.env.HOME ?? '', '.dsh-dev/profiles/web/node_modules/yaml'),
]
let parse, stringify
for (const dir of yamlCandidates) {
  try {
    const m = await import(join(dir, 'dist', 'index.js'))
    parse = m.parse ?? m.default?.parse
    stringify = m.stringify ?? m.default?.stringify
    if (parse && stringify) break
  } catch { /* try next */ }
}
if (!parse || !stringify) {
  console.error('gen-mutex-patch: could not resolve yaml; pass an explicit --context with a node_modules containing yaml')
  process.exit(1)
}

const header = `# Mutually-exclusive async-compaction overlay (DNMS01, -10/-14; QNA R-16; ACE-1117 -09/-10⑤).
#
# Generated by scripts/gen-mutex-patch.mjs — do not hand-edit the preset blocks.
# Each preset row below is a WHOLE-object config.plugins replay of the upstream
# preset file; only the "id: compaction" group differs inside (our Provider row
# is inserted and the factory compaction-basic row is disabled), and a top-level
# inspect-checkpoint tools row (the same package's ./tools export) is appended
# OUTSIDE the isolate. A trailing profile-root row disables the base bundle's
# flat compaction-basic so ON never leaves two providers. OFF = remove this
# bundle from dsh.profile.bundles and the native composition returns.
#
# Source presets: ${ctxDir}/\${standard,ptc,minimal,cordis}.patch.yml
#
`

const patches = []
const jsTag = { tag: 'tag:yaml.org,2002:js', resolve: v => v }
for (const key of PRESETS) {
  const file = join(ctxDir, `${key}.patch.yml`)
  const rows = parse(readFileSync(file, 'utf8'), { customTags: [jsTag] })
  const insert = rows.find(p => Array.isArray(p.insert))
  const preset = insert.insert.find(r => r.id === PRESET_IDS[key])
  if (!preset) throw new Error(`preset row ${PRESET_IDS[key]} not found in ${file}`)
  const plugins = preset.config.plugins.map(row =>
    VERSION_GUARDED_ROWS.has(row.id)
      ? { ...row, disabled: guardPlaceholder(VERSION_GUARDED_ROWS.get(row.id)) }
      : row)
  const ci = plugins.findIndex(r => r.id === 'compaction')
  if (ci < 0) throw new Error(`id:compaction group not found in preset ${key}`)
  const group = plugins[ci]
  const rows2 = group.config.map(row =>
    row.id === 'compaction-basic' ? { ...row, disabled: true } : row)
  const patched = { ...group, config: [PROVIDER_ROW, ...rows2] }
  // -09①: the tools row mounts at preset top level, NOT inside the isolate
  // group — it is a plain plugin ctx, so ctx.tools/session are injectable.
  const replay = plugins.map((r, i) => (i === ci ? patched : r)).concat(TOOLS_ROW)
  patches.push({ id: PRESET_IDS[key], config: { ...preset.config, plugins: replay } })
}

/**
 * -10⑤: `packages/bundle/base` also mounts a FLAT top-level compaction-basic
 * (not inside any isolate). ON must not leave a second compaction provider
 * alive at profile root, so the overlay pins that row disabled too.
 */
patches.push({ id: 'compaction-basic', disabled: true })

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'cordis.patch.yml')
let text = stringify(patches, { customTags: [jsTag] })
// yaml loses the !!js tag on round-trip; restore it wherever the source rows
// carried a code expression (identifiable by a leading `!` or `process.`/`ctx.`
// expression that upstream only ever writes as a !!js literal).
text = text.replace(
  /^(\s*disabled: )(?!!!js )(.*(?:process\.|ctx\.).*)$/gm,
  (_m, p, v) => `${p}!!js ${v}`,
)
text = text.replace(
  /^(\s*-\s*)"(!!js .*)"$/gm,
  '$1$2',
)
// Restore guarded-row placeholders into real `disabled: !!js …` lines.
for (const [, pkg] of VERSION_GUARDED_ROWS) {
  text = text.replace(
    new RegExp(`^(\\s*)disabled: ${guardPlaceholder(pkg).replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}$`, 'gm'),
    (_m, p) => `${p}${guardLine(pkg)}`,
  )
}
writeFileSync(out, header + text)
console.log(`wrote ${out} (${patches.length} preset replays)`)
