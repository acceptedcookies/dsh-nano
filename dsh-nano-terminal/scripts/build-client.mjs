import { createRequire } from 'node:module'
import { readFileSync, writeFileSync, rmSync, mkdirSync, copyFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const body = join(root, 'lib/client.body.js')

const require = createRequire(join(root, 'package.json'))
let esbuild
try {
  esbuild = require('esbuild')
} catch {
  console.error('[build] esbuild not installed — run `npm ci` first')
  process.exit(1)
}

mkdirSync(join(root, 'lib'), { recursive: true })

// Host halves: index.js is unbundled and imports ./lib/*.js at runtime. The dev
// instance copies lib/ but not node_modules — our host files have no external
// deps, so bundling is just concatenation for a stable lib/ surface.
for (const name of ['sessions', 'mcp', 'ws', 'mirror', 'events', 'errors', 'gate', 'wait']) {
  esbuild.buildSync({
    absWorkingDir: root, logLevel: 'warning',
    entryPoints: [`src/host/${name}.js`],
    bundle: true, format: 'esm', platform: 'node',
    outfile: join(root, `lib/${name}.js`),
  })
}

// wasm asset for the host mirror
copyFileSync(join(root, 'assets/dnt-core.wasm'), join(root, 'lib/dnt-core.wasm'))

// Browser half: IIFE inside the module-loader factory. wasm is embedded as
// base64 (src/client/wasm-b64.js generated by build-rust.sh).
esbuild.buildSync({
  absWorkingDir: root, logLevel: 'info',
  entryPoints: ['src/client/index.js'],
  bundle: true, format: 'iife', globalName: '__dntExport', minify: true,
  platform: 'browser',
  loader: { '.jsx': 'jsx' },
  external: ['react', 'react-dom', 'react-dom/client', '@deepseek-ai/dsh-client-ui-primitives'],
  outfile: body,
})

const source = readFileSync(body, 'utf8').trim()
writeFileSync(join(root, 'lib/client.js'), `window.__ModuleLoader__.load({
	id: "dsh-nano-terminal",
	factory: (require) => {
${source}
		return __dntExport;
	}
});
`)
rmSync(body)
console.log('[build] lib/client.js written')
