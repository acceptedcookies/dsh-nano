#!/usr/bin/env bash
# Build dnt-core to wasm32 and emit:
#   assets/dnt-core.wasm        (shipped for the host-side mirror)
#   src/client/wasm-b64.js      (embedded base64 for the browser bundle)
set -euo pipefail
cd "$(dirname "$0")/.."

cargo build --target wasm32-unknown-unknown --release -p dnt-core

WASM=target/wasm32-unknown-unknown/release/dnt_core.wasm
cp "$WASM" assets/dnt-core.wasm

node -e "
const fs = require('node:fs')
const b64 = fs.readFileSync('assets/dnt-core.wasm').toString('base64')
fs.mkdirSync('src/client', { recursive: true })
fs.writeFileSync('src/client/wasm-b64.js',
  '// GENERATED by scripts/build-rust.sh — do not edit\nexport default ' + JSON.stringify(b64) + '\n')
console.log('wasm-b64.js:', (b64.length / 1024).toFixed(1) + 'KB from', fs.statSync('assets/dnt-core.wasm').size + 'B')
"
