/**
 * dsh-interface/build — 构建期物化出口。
 * 把声明表烤成产物常量源码；产物自包含、离仓可读、不反调本出口。
 * 生成是幂等的：同输入字节级相等；改任一作者字段产物对应变化。
 */

/**
 * Deterministic JS literal serializer for baked ledger rows. Emits a stable,
 * byte-identical ordering so two runs over the same input produce identical
 * output (T03). Handlers are never serialized — the baked table is ledger data.
 */
function lit(value) {
  if (value === undefined) return 'undefined'
  return JSON.stringify(value)
}

const LEDGER_FIELDS = [
  'id', 'plugin', 'channel', 'match', 'path', 'methods',
  'bodyLimit', 'sensitivity', 'capability', 'sessionBinding', 'justification',
]

/**
 * bindingTableModule(rows, { plugin, constName }) → JS module source string.
 * `rows` are binding ledger declarations (id/channel/match/path/methods +
 * ledger fields). Output is `export const {constName} = [ ...frozen rows ]`.
 */
export function bindingTableModule(rows, { plugin, constName = 'BINDING_TABLE' } = {}) {
  if (!Array.isArray(rows)) throw new Error('binding-table: rows must be an array')
  const seen = new Set()
  const lines = rows.map(r => {
    if (!r || typeof r.id !== 'string' || r.id === '') {
      throw new Error('binding-table: every row needs a stable non-empty id')
    }
    if (seen.has(r.id)) throw new Error(`binding-table: duplicate id "${r.id}"`)
    seen.add(r.id)
    const fields = LEDGER_FIELDS
      .filter(f => r[f] !== undefined)
      .map(f => `${JSON.stringify(f)}:${lit(f === 'plugin' ? (r[f] ?? plugin) : r[f])}`)
      .join(', ')
    return `  { ${fields} },`
  })
  return [
    `// Baked binding table — generated by dsh-interface/build. Do not edit.`,
    `// plugin: ${plugin ?? 'unknown'}`,
    `export const ${constName} = Object.freeze([`,
    ...lines,
    `])`,
    ``,
  ].join('\n')
}


