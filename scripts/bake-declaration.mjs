#!/usr/bin/env node
/**
 * Bake the runtime slice of a plugin's performance declaration
 * (T-O-PRE1116-09.5): key names, interaction target buckets, and the
 * declaration hash. budgets / scenarios / contract never enter the bundle.
 *
 *   node scripts/bake-declaration.mjs --plugin <package-name>
 *   node scripts/bake-declaration.mjs --all
 */
import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { validateDeclaration } from '../packages/dsh-performance-review/src/declaration.js'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')

export const DECLARATION_PLUGINS = [
  'dsh-nano-explorer-extra',
  'dsh-nano-notepad',
  'dsh-nano-model-selector',
  'dsh-nano-cloud-session',
  'dsh-nano-terminal',
  'dsh-nano-local-sandbox',
  'dsh-nano-kitesurf',
]

function sourceFor(value) {
  const runtime = {
    keys: value.keys ?? { spans: [], tracks: [], usage: [], hostSpans: [] },
    buckets: value.buckets ?? [],
  }
  const hash = createHash('sha256').update(JSON.stringify(value)).digest('hex').slice(0, 12)
  return `/** GENERATED by scripts/bake-declaration.mjs from src/perf/declaration.json. Do not edit. */
export const KEYS = Object.freeze(${JSON.stringify(runtime.keys)})
export const BUCKETS = Object.freeze(${JSON.stringify(runtime.buckets)})
export const DECL_HASH = ${JSON.stringify(hash)}
`
}

function bake(plugin) {
  const path = join(ROOT, plugin, 'src', 'perf', 'declaration.json')
  const value = validateDeclaration(JSON.parse(readFileSync(path, 'utf8')))
  if (value.plugin !== plugin.replace(/^dsh-nano-/, 'nano-')) {
    throw new Error(`bake-declaration: ${plugin} declares plugin ${value.plugin}`)
  }
  const out = join(ROOT, plugin, 'lib', 'perf-declaration.js')
  mkdirSync(dirname(out), { recursive: true })
  writeFileSync(out, sourceFor(value))
  return out
}

function main() {
  const args = process.argv.slice(2)
  const i = args.indexOf('--plugin')
  const plugins = i >= 0 ? [args[i + 1]] : DECLARATION_PLUGINS
  for (const plugin of plugins) console.log(`baked ${bake(plugin)}`)
}

try { main() } catch (error) { console.error(error.message); process.exit(1) }
