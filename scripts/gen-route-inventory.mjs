#!/usr/bin/env node
/**
 * Regenerate security/route-inventory.md from the single authored ledger
 * (security/route-sensitivity.json). The inventory is a read-only projection;
 * edit the ledger, never this file (T-O-PRE1116-05 / P2-04).
 *
 *   node scripts/gen-route-inventory.mjs           # print
 *   node scripts/gen-route-inventory.mjs --write   # overwrite
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const LEDGER = join(ROOT, 'security', 'route-sensitivity.json')
const OUT = join(ROOT, 'security', 'route-inventory.md')

export function renderInventory(ledger) {
  const rows = ledger.routes ?? []
  const byPlugin = new Map()
  for (const row of rows) {
    if (!byPlugin.has(row.plugin)) byPlugin.set(row.plugin, [])
    byPlugin.get(row.plugin).push(row)
  }
  const lines = [
    '# Route inventory',
    '',
    `> GENERATED by \`scripts/gen-route-inventory.mjs\` from \`security/route-sensitivity.json\`.`,
    `> ${rows.length} active host routes. Edit the ledger, not this file.`,
    '',
    '`id` is the authored contract-surface identity; `channel`/`match` are the registrar axes.',
    '`session` marks a session-scoped route. `bodyLimit` is the route-level cap (GET/HEAD = 0).',
    '',
    '| plugin | routes | http | upgrade |',
    '|---|---|---|---|',
  ]
  for (const [plugin, list] of byPlugin) {
    const http = list.filter(row => row.channel === 'http').length
    const upgrade = list.filter(row => row.channel === 'upgrade').length
    lines.push(`| ${plugin} | ${list.length} | ${http} | ${upgrade} |`)
  }
  lines.push('')
  for (const [plugin, list] of byPlugin) {
    lines.push(`## ${plugin} — ${list.length}`)
    lines.push('')
    lines.push('| id | path | methods | channel | match | sensitivity | capability | bodyLimit | session |')
    lines.push('|---|---|---|---|---|---|---|---|---|')
    for (const row of list) {
      lines.push(`| \`${row.id}\` | \`${row.path}\` | ${row.methods.join(',')} | ${row.channel} | ${row.match} | ${row.sensitivity} | ${row.capability} | ${row.bodyLimit} | ${row.sessionBinding ? '✓' : '–'} |`)
    }
    lines.push('')
  }
  return lines.join('\n')
}

const ledger = JSON.parse(readFileSync(LEDGER, 'utf8'))
const markdown = renderInventory(ledger)
if (process.argv.includes('--write')) {
  writeFileSync(OUT, markdown)
  console.log(`wrote ${OUT} (${ledger.routes.length} routes)`)
} else {
  console.log(markdown)
}
